/**
 * Generates `src/screens/screenAssets.ts`: which `/figma/...` files each screen
 * draws.
 *
 * The assets live in `public/`, so Vite never sees them as modules and cannot
 * tell us what a screen needs. Rather than keep that list by hand - which would
 * be wrong the first time anyone adds an image - this walks each screen's own
 * import graph and collects the literals it finds.
 *
 * Run from the project root:
 *
 *     node tools/assets/screen-assets.mjs
 *
 * `screenAssets.test.ts` fails if the checked-in file has drifted from what
 * this produces, so a forgotten regeneration is caught by the suite rather than
 * by a student waiting on an image.
 */

import { readFileSync, writeFileSync, existsSync, statSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';

/** True only for a path that exists and is a file, never a directory. */
function isFile(path) {
  return existsSync(path) && statSync(path).isFile();
}

/** The screen names are the ones in `SCREENS` in `src/App.tsx`. */
const ENTRIES = {
  signIn: 'src/screens/onboarding/OnboardingScreen.tsx',
  prefixIntro: 'src/screens/prefixes/PrefixIntroScreen.tsx',
  alkane: 'src/screens/Alkane/AlkaneScreen.tsx',
  alkene: 'src/screens/Alkene/AlkeneScreen.tsx',
  alkyne: 'src/screens/Alkyne/AlkyneScreen.tsx',
  gameplay: 'src/screens/gameplay/GameplayFlow.tsx',
  play: 'src/screens/gameplay/live/LiveGameplay.tsx',
};

const ASSET = /\/figma\/[A-Za-z0-9_./-]+?\.(?:svg|png|jpg|jpeg|webp)/g;
const IMPORT = /(?:from|import)\s*\(?\s*['"](\.[^'"]+)['"]/g;

/** Resolves a relative specifier the way the bundler does. */
function resolveModule(fromFile, spec) {
  const base = resolve(dirname(fromFile), spec);
  const candidates = [
    base,
    `${base}.ts`,
    `${base}.tsx`,
    base.replace(/\.js$/, '.ts'),
    base.replace(/\.js$/, '.tsx'),
    join(base, 'index.ts'),
    join(base, 'index.tsx'),
  ];
  return candidates.find(isFile) ?? null;
}

/** Every `/figma/...` literal reachable from one entry module. */
function assetsFrom(entry) {
  const seen = new Set();
  const found = new Set();
  const queue = [resolve(entry)];

  while (queue.length > 0) {
    const file = queue.pop();
    if (!file || seen.has(file)) continue;
    seen.add(file);
    if (!isFile(file)) continue;

    const source = readFileSync(file, 'utf8');
    for (const match of source.matchAll(ASSET)) found.add(match[0]);
    for (const [, spec] of source.matchAll(IMPORT)) {
      const next = resolveModule(file, spec);
      if (next) queue.push(next);
    }
  }
  return [...found].sort();
}

const byScreen = Object.fromEntries(
  Object.entries(ENTRIES).map(([screen, entry]) => [screen, assetsFrom(entry)]),
);

const lines = Object.entries(byScreen)
  .map(([screen, assets]) => {
    const items = assets.map((a) => `    '${a}',`).join('\n');
    return `  ${screen}: [\n${items}\n  ],`;
  })
  .join('\n');

const out = `// Generated by tools/assets/screen-assets.mjs - do not edit by hand.
//
// Which images each screen draws, so the one after it can be fetched while the
// student is still reading this one. Assets live in \`public/\`, so the bundler
// cannot work this out for us.

export const SCREEN_ASSETS: Record<string, readonly string[]> = {
${lines}
};

/** The images a screen draws, or nothing for a screen that draws none. */
export function assetsForScreen(screen: string): readonly string[] {
  return SCREEN_ASSETS[screen] ?? [];
}
`;

writeFileSync('src/screens/screenAssets.ts', out);

for (const [screen, assets] of Object.entries(byScreen)) {
  console.log(`${screen.padEnd(14)} ${String(assets.length).padStart(3)} assets`);
}
